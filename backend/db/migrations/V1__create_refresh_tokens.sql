-- V1: refresh token store for cookie-based JWT authentication.
--
-- Review, then run ONCE against the target database (for example in the
-- Supabase SQL editor, which runs as the postgres role) before starting the
-- backend with spring.jpa.hibernate.ddl-auto=validate. It only creates a new
-- table; it does not read or modify any existing table or row.
--
-- Only SHA-256 hashes of refresh tokens are stored, never the tokens themselves.
-- Rollback: V1__create_refresh_tokens.rollback.sql
-- Verify:   ../verify/verify_security.sql

BEGIN;

CREATE TABLE IF NOT EXISTS public.refresh_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT                      NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    token_hash  VARCHAR(64)                 NOT NULL UNIQUE,
    family_id   VARCHAR(36)                 NOT NULL,
    persistent  BOOLEAN                     NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    revoked_at  TIMESTAMP(6) WITH TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_refresh_tokens_user_id   ON public.refresh_tokens (user_id);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_family_id ON public.refresh_tokens (family_id);

-- Supabase exposes tables in the public schema through its Data API, and its
-- default privileges grant the anon and authenticated roles full access to new
-- tables. This application never uses that API, so:
--   * RLS with no policies hides every row from those roles, and
--   * revoking their privileges also removes TRUNCATE, which RLS does not cover.
-- The backend connects as postgres, the table owner with BYPASSRLS, so its
-- access is unaffected.
ALTER TABLE public.refresh_tokens ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.refresh_tokens FROM anon, authenticated;

COMMIT;
